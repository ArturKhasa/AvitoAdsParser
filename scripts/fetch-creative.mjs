function randomHex(bytes = 32) {
  return Array.from({ length: bytes }, () =>
      Math.floor(Math.random() * 256).toString(16).padStart(2, '0')
  ).join('');
}

async function getExitIp(dispatcher, signal) {
  try {
    const res = await fetch('https://api.ipify.org?format=json', { dispatcher, signal });
    const { ip } = await res.json();
    return ip;
  } catch {
    return null;
  }
}

// Открываем avito.ru как браузер: собираем cookies и случайную паузу
async function visitAvitoAndGetCookies(dispatcher, signal) {
  try {
    const res = await fetch('https://www.avito.ru/', {
      method: 'GET',
      headers: HEADERS_PAGE,
      dispatcher,
      signal,
    });
    // getSetCookie() возвращает массив строк вида "name=value; Path=/; ..."
    const setCookies = res.headers.getSetCookie?.() ?? [];
    const cookieStr = setCookies
        .map((c) => c.split(';')[0].trim())  // берём только name=value
        .filter(Boolean)
        .join('; ');
    return cookieStr;
  } catch {
    return '';
  }
}

